import io
import random

from PIL import Image, ImageDraw
from django.core.management.base import BaseCommand
from django.utils.text import slugify

from apps.gyms.image_hosting import ImageHostingError, upload_image
from apps.gyms.models import Gym, GymImage


PALETTES = [
    ((16, 16, 16), (47, 124, 255)),
    ((19, 21, 26), (110, 231, 183)),
    ((23, 17, 31), (249, 115, 22)),
    ((17, 24, 39), (167, 139, 250)),
    ((15, 23, 42), (244, 63, 94)),
]


class Command(BaseCommand):
    help = 'Generate remote ImgBB placeholder covers for gyms that do not have photos yet.'

    def add_arguments(self, parser):
        parser.add_argument('--source', default='')
        parser.add_argument('--city', default='')
        parser.add_argument('--limit', type=int, default=0)
        parser.add_argument('--replace', action='store_true')
        parser.add_argument('--approve-only', action='store_true')
        parser.add_argument('--dry-run', action='store_true')

    def handle(self, *args, **options):
        qs = Gym.objects.all().order_by('id')
        if options['source']:
            qs = qs.filter(source=options['source'])
        if options['city']:
            qs = qs.filter(city__iexact=options['city'])
        if options['approve_only']:
            qs = qs.filter(status=Gym.Status.APPROVED)

        if not options['replace']:
            qs = qs.filter(images__isnull=True)
        else:
            qs = qs.distinct()

        limit = options['limit']
        gyms = list(qs[:limit] if limit and limit > 0 else qs)
        if not gyms:
            self.stdout.write(self.style.WARNING('No gyms matched, or all matched gyms already have photos.'))
            return

        if options['dry_run']:
            for gym in gyms[:30]:
                self.stdout.write(f'DRY: would generate remote cover for #{gym.id} {gym.name}')
            self.stdout.write(self.style.SUCCESS(f'Dry run complete: {len(gyms)} gym(s) matched.'))
            return

        created = 0
        failed = 0
        for gym in gyms:
            if options['replace']:
                gym.images.filter(source__in=['placeholder', 'imgbb_placeholder']).delete()

            content = self._png_for_gym(gym)
            filename = f'{gym.id}-{slugify(gym.name)[:60] or "gym"}.png'
            content.name = filename
            try:
                hosted = upload_image(content, name=filename)
            except ImageHostingError as exc:
                failed += 1
                self.stderr.write(self.style.ERROR(f'FAIL #{gym.id} {gym.name}: {exc}'))
                continue

            GymImage.objects.create(
                gym=gym,
                external_url=hosted.url,
                source='imgbb_placeholder',
                credit='Generated by myGym and hosted on ImgBB',
                remote_id=hosted.id,
                remote_delete_url=hosted.delete_url,
                remote_width=hosted.width,
                remote_height=hosted.height,
                remote_size=hosted.size,
                alt_text=f'{gym.name} cover image',
                is_cover=not gym.images.exists(),
            )
            created += 1

        message = f'Generated {created} remote placeholder photo(s).'
        if failed:
            message += f' {failed} failed.'
            self.stdout.write(self.style.WARNING(message))
        else:
            self.stdout.write(self.style.SUCCESS(message))

    def _png_for_gym(self, gym):
        seed = gym.id or sum(ord(c) for c in gym.name)
        random.seed(seed)
        bg, accent = random.choice(PALETTES)
        width, height = 1400, 900
        image = Image.new('RGB', (width, height), bg)
        draw = ImageDraw.Draw(image)
        draw.rectangle((0, height * 0.65, width, height), fill=accent)
        draw.ellipse((width - 360, 80, width - 80, 360), outline=(255, 255, 255), width=16)
        draw.text((110, 120), 'myGym', fill=(255, 255, 255))
        draw.text((110, 190), gym.city or 'Fitness', fill=(225, 225, 225))
        draw.text((110, 520), gym.name[:48], fill=(255, 255, 255))
        draw.text((110, 590), 'Fitness · Training · Wellness', fill=(240, 240, 240))
        buffer = io.BytesIO()
        image.save(buffer, format='PNG', optimize=True)
        buffer.seek(0)
        return buffer
